"""
GeoReckon Kotlin Client Protocol Integration Test
Simulates the exact payload models, serialization formats, and lifecycle events
generated by the Kotlin Android Socket.IO client (GeoReckonSocketIOClient).

Verifies:
1. Successful Socket.IO connection
2. Full Calibration with 50 pre-outage IMU samples & 3 GPS points
3. Stream of 100 Sensor packets (10 Hz cadence)
4. Position telemetry reception and validation (speed, bearing, mode, confidence, KinoNet shadow)
5. GPS Restored restitution
6. Session Reset and IDLE state restoration
7. Measured client-server round-trip latency
"""

import time
import unittest
import numpy as np

from georeckon.server.app import app, socketio, sessions


class TestKotlinAndroidClientProtocolIntegration(unittest.TestCase):
    def setUp(self):
        sessions.clear()
        self.client = socketio.test_client(app)
        self.assertTrue(self.client.is_connected(), "Socket.IO client failed to connect")

    def tearDown(self):
        if self.client.is_connected():
            self.client.disconnect()
        sessions.clear()

    def test_kotlin_client_end_to_end_lifecycle_100_packets(self):
        # 1. Connection established
        session_id = "sess_kotlin_android_001"
        t0_ms = 1727632400000

        # 2. Build Kotlin-equivalent CalibrateRequest payload (50 IMU samples, 3 GPS points)
        imu_history = []
        for i in range(50):
            imu_history.append({
                "t_ms": t0_ms - 5000 + (i * 100),
                "accel": [0.8 + 0.02 * i, 0.0, 9.80665], # forward acceleration
                "gyro": [0.0, 0.0, 0.0],
                "gravity": [0.0, 0.0, 9.80665]
            })

        gps_history = [
            {"t_ms": t0_ms - 5000, "speed_mps": 10.0, "bearing_deg": 90.0},
            {"t_ms": t0_ms - 2500, "speed_mps": 12.0, "bearing_deg": 90.0},
            {"t_ms": t0_ms, "speed_mps": 14.0, "bearing_deg": 90.0}
        ]

        cal_request = {
            "session_id": session_id,
            "seq": 1,
            "t_ms": t0_ms,
            "sample_rate_hz": 10.0,
            "allow_low_health": False,
            "last_gps": {
                "lat": 12.9715987,
                "lon": 77.5945627,
                "alt_m": 920.5,
                "speed_mps": 14.0,
                "bearing_deg": 90.0,
                "accuracy_m": 2.0
            },
            "gps_history": gps_history,
            "imu_history": imu_history
        }

        # Send calibrate
        self.client.emit("calibrate", cal_request)
        received = self.client.get_received()
        self.assertEqual(len(received), 1, "Expected 1 calibrate_done response")
        self.assertEqual(received[0]["name"], "calibrate_done")
        cal_done = received[0]["args"][0]
        self.assertEqual(cal_done["status"], "OK")
        self.assertFalse(cal_done["degraded"])
        self.assertGreaterEqual(cal_done["alignment_health"], 0.25)
        print(f"\n[Kotlin Client Integration] Calibrate success: alignment_health={cal_done['alignment_health']:.2f}, degraded={cal_done['degraded']}")

        # 3. Stream 100 sensor packets at 10 Hz (seq 2..101)
        latencies = []
        positions_received = 0
        t_stream = t0_ms

        for i in range(1, 101):
            t_stream += 100
            seq_num = i + 1
            sensor_packet = {
                "session_id": session_id,
                "seq": seq_num,
                "t_ms": t_stream,
                "accel": [0.05, 0.0, 9.80665],
                "gyro": [0.0, 0.0, 0.005],
                "gravity": [0.0, 0.0, 9.80665]
            }

            t_send = time.perf_counter()
            self.client.emit("sensor", sensor_packet)
            rec = self.client.get_received()
            rtt_ms = (time.perf_counter() - t_send) * 1000.0
            latencies.append(rtt_ms)

            self.assertEqual(len(rec), 1, f"Expected 1 position response on packet #{i}")
            self.assertEqual(rec[0]["name"], "position")
            pos = rec[0]["args"][0]
            self.assertEqual(pos["session_id"], session_id)
            self.assertEqual(pos["seq"], seq_num)
            self.assertEqual(pos["mode"], "DEAD_RECKONING")
            positions_received += 1

            if i == 1 or i == 50 or i == 100:
                print(f"  [Packet #{i:03d} | seq={seq_num}] lat={pos['lat']:.6f}, lon={pos['lon']:.6f}, speed={pos['speed_mps']:.2f} m/s, dist={pos['dr_distance_m']:.1f} m, kinonet_spd={pos['kinonet_speed_mps']:.2f} m/s, rtt={rtt_ms:.2f} ms")

        self.assertEqual(positions_received, 100)
        mean_lat = float(np.mean(latencies))
        p95_lat = float(np.percentile(latencies, 95))
        max_lat = float(np.max(latencies))
        print(f"[Kotlin Client Stream Stats (100 packets)] Mean={mean_lat:.2f} ms, p95={p95_lat:.2f} ms, Max={max_lat:.2f} ms")

        # 4. GPS Restored event
        gps_restored_packet = {
            "session_id": session_id,
            "seq": 102,
            "t_ms": t_stream + 100,
            "gps": {
                "lat": 12.9715987,
                "lon": 77.5960000,
                "alt_m": 920.5,
                "speed_mps": 14.2,
                "bearing_deg": 90.0,
                "accuracy_m": 2.5
            }
        }
        self.client.emit("gps_restored", gps_restored_packet)
        rec_restored = self.client.get_received()
        self.assertEqual(len(rec_restored), 1)
        self.assertEqual(rec_restored[0]["name"], "position")
        final_pos = rec_restored[0]["args"][0]
        self.assertEqual(final_pos["mode"], "IDLE")
        self.assertIsNotNone(final_pos["dr_error_m"])
        print(f"[Kotlin Client GPS Restored] Outage completed: mode={final_pos['mode']}, dr_error={final_pos['dr_error_m']:.2f} m, total_dr_distance={final_pos['dr_distance_m']:.2f} m")

        # 5. Session Reset
        reset_packet = {
            "session_id": session_id,
            "seq": 1,
            "t_ms": t_stream + 200
        }
        self.client.emit("reset", reset_packet)
        rec_reset = self.client.get_received()
        self.assertEqual(len(rec_reset), 1)
        self.assertEqual(rec_reset[0]["name"], "reset_done")
        self.assertEqual(rec_reset[0]["args"][0]["status"], "OK")
        self.assertEqual(rec_reset[0]["args"][0]["mode"], "IDLE")
        print(f"[Kotlin Client Reset] Session reset confirmed: status={rec_reset[0]['args'][0]['status']}, mode={rec_reset[0]['args'][0]['mode']}")


if __name__ == "__main__":
    unittest.main()
